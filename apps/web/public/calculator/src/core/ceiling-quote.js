/** Площадь панели 0,75 × 0,55 м. Общая формула сметы по площади потолка. */
export const CEILING_PANEL_AREA_M2 = 0.75 * 0.55;

/**
 * Сколько панелей закрывает площадь потолка, если обрезки считаются использованными.
 * Прямоугольник в калькуляторе считает иначе: раскладка 0,75×0,55 не заполняет
 * комнату без подрезки, поэтому панелей к закупке больше.
 */
export function panelsForCeilingArea(areaM2) {
  if (!(Number(areaM2) > 0)) return 0;
  return Math.ceil(Number(areaM2) / CEILING_PANEL_AREA_M2);
}
